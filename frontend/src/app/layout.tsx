import type { Metadata, Viewport } from "next";
import localFont from "next/font/local";
import { cookies, headers } from "next/headers";
import Script from "next/script";

import { brand } from "@/config/brand";
import { i18nConfig } from "@/config/i18n";
import { site } from "@/config/site";
import { loadMessages } from "@/lib/i18n/messages";
import { resolveRequestLocale } from "@/lib/i18n/request-locale";
import { AppProviders } from "@/providers/app-providers";

import "./globals.css";

// Self-hosted (TEC-141): the build must not depend on fonts.googleapis.com.
// Files and OFL licenses live in ./fonts, regenerated by
// scripts/build-fonts.py. Each file is a variable font cut to the weights
// below; scripts a family lacks use the fallback stack in styles/theme.css.
const plusJakarta = localFont({
  src: "./fonts/plus-jakarta-sans-wght.woff2",
  variable: "--font-jakarta",
  weight: "400 700",
  display: "swap",
});

const outfit = localFont({
  src: "./fonts/outfit-wght.woff2",
  variable: "--font-outfit",
  weight: "500 700",
  display: "swap",
});

const jetbrainsMono = localFont({
  src: "./fonts/jetbrains-mono-wght.woff2",
  variable: "--font-jetbrains",
  weight: "400 500",
  display: "swap",
});

export const metadata: Metadata = {
  metadataBase: new URL(site.url),
  title: {
    default: brand.productName,
    template: `%s · ${brand.name}`,
  },
  description: brand.tagline,
  applicationName: brand.productName,
  openGraph: {
    type: "website",
    siteName: site.name,
    locale: site.locale,
    images: [site.ogImage],
  },
  twitter: { card: "summary_large_image", images: [site.ogImage.url] },
};

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: brand.colors.mist },
    { media: "(prefers-color-scheme: dark)", color: brand.colors.ink },
  ],
};

/**
 * TEC-628: Linear revision-request widget (issue.technowide.tr). The script
 * builds its own button, Shadow DOM and iframe; the allowed origin, Linear
 * team and project mapping live on the widget server (/configure), so no
 * Linear credential is needed here. Loaded once, in the root layout, with
 * afterInteractive: it reads its data-* options from document.currentScript
 * and guards against a second load with the #lpi-embed-host id. It must run
 * in the top-level document (not inside an iframe) for the screenshot flow.
 */
const FEEDBACK_WIDGET_SRC = "https://issue.technowide.tr/embed.js";

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Language, direction and zone come from cookies (TEC-137) so the server
  // writes the right <html lang dir> and text on the first paint: no LTR
  // flash for Arabic, and the choice survives a reload before Me loads.
  // Without the language cookie (anonymous first visit) the browser's
  // Accept-Language decides (TEC-142).
  const store = await cookies();
  const requestHeaders = await headers();
  const { locale, dir, timeZone } = resolveRequestLocale(
    (name) => store.get(name)?.value,
    requestHeaders.get("accept-language"),
  );
  // en is bundled on the client; any other language is handed over so the
  // hydration render matches the server render.
  const messages =
    locale === i18nConfig.fallbackLocale ? null : await loadMessages(locale);

  return (
    <html lang={locale} dir={dir} suppressHydrationWarning className="h-full">
      <body
        className={`${plusJakarta.variable} ${outfit.variable} ${jetbrainsMono.variable} min-h-full font-sans antialiased`}
      >
        <AppProviders locale={locale} messages={messages} timeZone={timeZone}>
          {children}
        </AppProviders>
        <Script
          id="technowide-issue-widget"
          src={FEEDBACK_WIDGET_SRC}
          strategy="afterInteractive"
        />
      </body>
    </html>
  );
}
