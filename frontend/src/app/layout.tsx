import type { Metadata, Viewport } from "next";
import localFont from "next/font/local";
import { cookies } from "next/headers";

import { brand } from "@/config/brand";
import {
  i18nConfig,
  localeDir,
  normalizeLocale,
  type AppLocale,
} from "@/config/i18n";
import { site } from "@/config/site";
import { isValidTimeZone } from "@/lib/i18n/format";
import { loadMessages } from "@/lib/i18n/messages";
import { AppProviders } from "@/providers/app-providers";

import "./globals.css";

// Self-hosted (TEC-141): the build must not depend on fonts.googleapis.com.
// Files and OFL licenses live in ./fonts, regenerated by
// scripts/build-fonts.py. Each file is a variable font cut to the weights
// below; scripts a family lacks use the fallback stack in styles/theme.css.
const plusJakarta = localFont({
  src: "./fonts/plus-jakarta-sans-wght.woff2",
  variable: "--font-jakarta",
  weight: "400 700",
  display: "swap",
});

const outfit = localFont({
  src: "./fonts/outfit-wght.woff2",
  variable: "--font-outfit",
  weight: "500 700",
  display: "swap",
});

const jetbrainsMono = localFont({
  src: "./fonts/jetbrains-mono-wght.woff2",
  variable: "--font-jetbrains",
  weight: "400 500",
  display: "swap",
});

export const metadata: Metadata = {
  metadataBase: new URL(site.url),
  title: {
    default: brand.productName,
    template: `%s · ${brand.name}`,
  },
  description: brand.tagline,
  applicationName: brand.productName,
  openGraph: {
    type: "website",
    siteName: site.name,
    locale: site.locale,
  },
};

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: brand.colors.mist },
    { media: "(prefers-color-scheme: dark)", color: brand.colors.ink },
  ],
};

/**
 * Language and time zone come from cookies (TEC-137) so the server writes
 * the right <html lang dir> and text on the first paint: no LTR flash for
 * Arabic, and the choice survives a reload before Me is fetched.
 */
async function resolveLocaleCookies(): Promise<{
  locale: AppLocale;
  timeZone: string;
}> {
  const store = await cookies();
  const locale =
    normalizeLocale(store.get(i18nConfig.cookieName)?.value) ??
    i18nConfig.defaultLocale;
  const zone = store.get(i18nConfig.timeZoneCookieName)?.value;
  const timeZone =
    zone && isValidTimeZone(zone) ? zone : i18nConfig.defaultTimeZone;
  return { locale, timeZone };
}

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const { locale, timeZone } = await resolveLocaleCookies();
  // en is bundled on the client; any other language is handed over so the
  // hydration render matches the server render.
  const messages =
    locale === i18nConfig.fallbackLocale ? null : await loadMessages(locale);

  return (
    <html
      lang={locale}
      dir={localeDir(locale)}
      suppressHydrationWarning
      className="h-full"
    >
      <body
        className={`${plusJakarta.variable} ${outfit.variable} ${jetbrainsMono.variable} min-h-full font-sans antialiased`}
      >
        <AppProviders locale={locale} messages={messages} timeZone={timeZone}>
          {children}
        </AppProviders>
      </body>
    </html>
  );
}
