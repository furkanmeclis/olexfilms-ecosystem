#!/usr/bin/env node
/**
 * Generates the per-language catalog wiring (TEC-137):
 *   - src/locales/<locale>/index.ts   imports every namespace JSON
 *   - src/lib/i18n/catalog-loaders.ts one dynamic import() per language
 * and creates an empty `{}` namespace file for a language that lacks one
 * (missing keys fall back to en at runtime; check-i18n warns).
 *
 * Languages come from SUPPORTED_LOCALES in src/config/i18n.ts, namespaces
 * from src/locales/en/*.json.
 *
 *   node scripts/gen-locale-catalogs.mjs           # write
 *   node scripts/gen-locale-catalogs.mjs --check   # exit 1 when stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import * as prettier from "prettier";

const FRONTEND = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const LOCALES_DIR = path.join(FRONTEND, "src/locales");
const CONFIG = path.join(FRONTEND, "src/config/i18n.ts");
const LOADERS = path.join(FRONTEND, "src/lib/i18n/catalog-loaders.ts");
const CHECK = process.argv.includes("--check");
const HEADER =
  "// Generated by scripts/gen-locale-catalogs.mjs (pnpm i18n:gen). Do not edit.\n";

export function readSupportedLocales(configSrc) {
  const m = configSrc.match(/SUPPORTED_LOCALES\s*=\s*\[([\s\S]*?)\]/);
  if (!m) throw new Error("SUPPORTED_LOCALES not found in src/config/i18n.ts");
  return [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

const locales = readSupportedLocales(fs.readFileSync(CONFIG, "utf8"));
const namespaces = fs
  .readdirSync(path.join(LOCALES_DIR, "en"))
  .filter((n) => n.endsWith(".json"))
  .map((n) => n.slice(0, -5))
  .sort();

const ident = (ns) =>
  ns.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase());

function indexSource() {
  const imports = namespaces
    .map((ns) => `import ${ident(ns)} from "./${ns}.json";`)
    .join("\n");
  const fields = namespaces
    .map((ns) => (ident(ns) === ns ? `  ${ns},` : `  "${ns}": ${ident(ns)},`))
    .join("\n");
  return `${HEADER}import type { LocaleCatalog } from "@/lib/i18n/types";

${imports}

const catalog: LocaleCatalog = {
${fields}
};

export default catalog;
`;
}

function loadersSource() {
  const rows = locales
    .map((l) => {
      const key = /^[a-z]+$/.test(l) ? l : `"${l}"`;
      return `  ${key}: () => import("@/locales/${l}").then((m) => m.default),`;
    })
    .join("\n");
  return `${HEADER}import type { AppLocale } from "@/config/i18n";
import type { LocaleCatalog } from "@/lib/i18n/types";

/** One chunk per language; en is also imported statically (fallback). */
export const catalogLoaders: Record<AppLocale, () => Promise<LocaleCatalog>> = {
${rows}
};
`;
}

const stale = [];
async function write(file, raw) {
  const options = (await prettier.resolveConfig(file)) ?? {};
  const content = await prettier.format(raw, { ...options, filepath: file });
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === content) return;
  stale.push(path.relative(FRONTEND, file));
  if (!CHECK) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}

for (const locale of locales) {
  const dir = path.join(LOCALES_DIR, locale);
  for (const ns of namespaces) {
    const file = path.join(dir, `${ns}.json`);
    if (!fs.existsSync(file)) await write(file, "{}\n");
  }
  await write(path.join(dir, "index.ts"), indexSource());
}
await write(LOADERS, loadersSource());

if (stale.length) {
  console.log(
    `${CHECK ? "Stale" : "Wrote"} ${stale.length} file(s):\n  ${stale.join("\n  ")}`,
  );
}
process.exit(CHECK && stale.length ? 1 : 0);
