import * as Haptics from 'expo-haptics';
import { type Href, router } from 'expo-router';
import { Alert } from 'react-native';

import { ApiError, isApiError } from '@/core/api/errors';
import { errorMessage, i18n } from '@/core/i18n';
import type { StatusTone } from '@/ui/status-pill';

import type { StockCountStatus, StockEntryStatus, TransferStatus } from './api';

/**
 * Message for a failed warehouse call: the web errors catalog first, then the
 * warehouse catalog (warehouse-only codes), then the generic text.
 */
export function whError(e: unknown): string {
  if (!isApiError(e)) return i18n.t('common:error_generic');
  if (e.code === 'NETWORK_ERROR') return i18n.t('common:error_network');
  const own = `warehouse:errors.${e.code}`;
  if (i18n.exists(own)) return i18n.t(own);
  return errorMessage(e.code);
}

export function isCode(e: unknown, code: string) {
  return e instanceof ApiError && e.code === code;
}

/** Error haptic + alert; used by every failed action. */
export function alertError(e: unknown) {
  void Haptics.notificationAsync(Haptics.NotificationFeedbackType.Error);
  Alert.alert(whError(e));
}

/** Asks before an irreversible step. */
export function confirmAction(opts: { title: string; body?: string; action: string; destructive?: boolean; onConfirm: () => void }) {
  Alert.alert(opts.title, opts.body, [
    { text: i18n.t('common:cancel'), style: 'cancel' },
    { text: opts.action, style: opts.destructive ? 'destructive' : 'default', onPress: opts.onConfirm },
  ]);
}

export function formatDate(iso: string | null | undefined, withTime = true) {
  if (!iso) return '';
  const d = new Date(iso);
  return new Intl.DateTimeFormat(i18n.language, {
    day: 'numeric',
    month: 'short',
    ...(withTime ? { hour: '2-digit', minute: '2-digit' } : { year: 'numeric' }),
  }).format(d);
}

export function formatNumber(n: number | string | null | undefined, digits = 0) {
  if (n === null || n === undefined || n === '') return '';
  const v = typeof n === 'string' ? Number(n) : n;
  if (!Number.isFinite(v)) return String(n);
  return new Intl.NumberFormat(i18n.language, { maximumFractionDigits: digits, minimumFractionDigits: 0 }).format(v);
}

export function transferTone(s: TransferStatus): StatusTone {
  return s === 'completed' ? 'done' : s === 'cancelled' ? 'problem' : s === 'in_transit' ? 'progress' : 'neutral';
}

export function countTone(s: StockCountStatus): StatusTone {
  return s === 'approved' ? 'done' : s === 'cancelled' ? 'problem' : s === 'draft' ? 'neutral' : 'progress';
}

export function entryTone(s: StockEntryStatus): StatusTone {
  return s === 'confirmed' ? 'done' : s === 'cancelled' || s === 'undone' ? 'problem' : 'neutral';
}

/**
 * Typed routes are generated by the dev server; screens added since then are
 * not in the generated union yet, so dynamic paths go through this.
 */
export function go(path: string) {
  router.push(path as Href);
}

export function replace(path: string) {
  router.replace(path as Href);
}
