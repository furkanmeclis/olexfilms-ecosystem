#!/usr/bin/env node
/**
 * Writes src/core/i18n/resources.ts: static imports of every language and
 * namespace under src/core/i18n/locales, plus the web's errors.json per
 * language (API error codes are translated once, in frontend/src/locales).
 *
 * Usage: pnpm i18n:gen   (after adding a namespace JSON file)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { LANGUAGES } from './i18n-languages.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const localesDir = path.join(root, 'src/core/i18n/locales');
const out = path.join(root, 'src/core/i18n/resources.ts');

const namespaces = fs
  .readdirSync(path.join(localesDir, 'en'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort((a, b) => (a === 'common' ? -1 : b === 'common' ? 1 : a.localeCompare(b)));

const id = (lang, ns) => `${lang.replace('-', '')}_${ns}`;
const lines = ['// Generated by scripts/gen-i18n-resources.mjs. Do not edit; run `pnpm i18n:gen`.', ''];
for (const lang of LANGUAGES) {
  for (const ns of namespaces) lines.push(`import ${id(lang, ns)} from './locales/${lang}/${ns}.json';`);
  lines.push(`import ${id(lang, 'errors')} from '../../../../frontend/src/locales/${lang}/errors.json';`);
}
const all = [...namespaces, 'errors'];
lines.push('', `export const NAMESPACES = [${all.map((n) => `'${n}'`).join(', ')}] as const;`, '', 'export const resources = {');
for (const lang of LANGUAGES) {
  const key = lang.includes('-') ? `'${lang}'` : lang;
  lines.push(`  ${key}: { ${all.map((n) => `${n}: ${id(lang, n)}`).join(', ')} },`);
}
lines.push('};', '');
fs.writeFileSync(out, lines.join('\n'));
console.log(`resources.ts: ${LANGUAGES.length} languages × ${all.length} namespaces`);
