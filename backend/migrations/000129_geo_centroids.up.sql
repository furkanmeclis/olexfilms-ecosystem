-- TEC-494 (F5-05e): geographic centroids for the performance region map.
-- TR province centroids use provincial center coordinates; districts are
-- nullable and can be filled incrementally by platform geo tooling.

ALTER TABLE provinces
    ADD COLUMN latitude  NUMERIC(9,6) NULL,
    ADD COLUMN longitude NUMERIC(9,6) NULL,
    ADD CONSTRAINT chk_provinces_centroid_pair
        CHECK ((latitude IS NULL) = (longitude IS NULL)),
    ADD CONSTRAINT chk_provinces_latitude_range
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    ADD CONSTRAINT chk_provinces_longitude_range
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180);

ALTER TABLE districts
    ADD COLUMN latitude  NUMERIC(9,6) NULL,
    ADD COLUMN longitude NUMERIC(9,6) NULL,
    ADD CONSTRAINT chk_districts_centroid_pair
        CHECK ((latitude IS NULL) = (longitude IS NULL)),
    ADD CONSTRAINT chk_districts_latitude_range
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    ADD CONSTRAINT chk_districts_longitude_range
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180);

