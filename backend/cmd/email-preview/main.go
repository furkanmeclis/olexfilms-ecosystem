// Command email-preview renders every e-mail the backend sends with sample
// data for each locale, without a database or network (TEC-1235):
//
//	go run ./cmd/email-preview -out ./tmp/email-preview [-locale tr,en,ar]
//
// It writes <type>.<locale>.html and .txt per e-mail and an index.html
// listing them by type and locale with subject and preheader.
package main

import (
	"context"
	"flag"
	"fmt"
	"html"
	"os"
	"path/filepath"
	"strings"

	"github.com/furkanmeclis/olexfilms-ecosystem/backend/internal/emailpreview"
	"github.com/furkanmeclis/olexfilms-ecosystem/backend/internal/platform/i18n"
)

func main() {
	out := flag.String("out", "./tmp/email-preview", "output directory")
	locales := flag.String("locale", "", "comma-separated locales (default: all supported)")
	flag.Parse()
	if err := run(*out, *locales); err != nil {
		fmt.Fprintln(os.Stderr, "email-preview:", err)
		os.Exit(1)
	}
}

func run(dir, localeList string) error {
	var locales []string
	for _, l := range strings.Split(localeList, ",") {
		if l = strings.TrimSpace(l); l != "" {
			locales = append(locales, l)
		}
	}
	samples, err := emailpreview.Build(context.Background(), locales)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, s := range samples {
		base := fileBase(s)
		if err := os.WriteFile(filepath.Join(dir, base+".html"), []byte(s.HTML), 0o644); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(dir, base+".txt"), []byte(s.Text), 0o644); err != nil {
			return err
		}
	}
	if err := os.WriteFile(filepath.Join(dir, "index.html"), []byte(index(samples)), 0o644); err != nil {
		return err
	}
	fmt.Printf("email-preview: %d e-mails written to %s (open index.html)\n", len(samples), dir)
	return nil
}

func fileBase(s emailpreview.Sample) string {
	r := strings.NewReplacer("/", "_", " ", "_", ":", "_")
	return r.Replace(s.Type) + "." + s.Locale
}

func index(samples []emailpreview.Sample) string {
	esc := html.EscapeString
	var b strings.Builder
	b.WriteString(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>E-mail preview</title>
<style>body{font-family:Arial,Helvetica,sans-serif;margin:24px;color:#18181b;background:#fff}h1{font-size:22px}h2{font-size:17px;margin:32px 0 4px}h3{font-size:14px;margin:20px 0 6px;font-family:monospace}
table{border-collapse:collapse;width:100%;font-size:13px}td,th{border:1px solid #e4e4e7;padding:6px 8px;vertical-align:top;text-align:start}th{background:#f4f4f5}.muted{color:#71717a}
nav a{margin-inline-end:12px}@media (prefers-color-scheme:dark){body{background:#18181b;color:#f4f4f5}th{background:#27272a}td,th{border-color:#3f3f46}a{color:#93c5fd}}</style></head><body>`)
	b.WriteString(`<h1>E-mail preview</h1><p class="muted">` + fmt.Sprint(len(samples)) + ` e-mails. Generated by <code>go run ./cmd/email-preview</code> with sample data (no database).</p>`)
	groups := []string{emailpreview.GroupNotification, emailpreview.GroupAlarm, emailpreview.GroupFleet, emailpreview.GroupCampaign}
	b.WriteString("<nav>")
	for _, g := range groups {
		b.WriteString(`<a href="#` + g + `">` + g + `</a>`)
	}
	b.WriteString("</nav>")
	for _, g := range groups {
		b.WriteString(`<h2 id="` + g + `">` + g + `</h2>`)
		typ := ""
		for _, s := range samples {
			if s.Group != g {
				continue
			}
			if s.Type != typ {
				if typ != "" {
					b.WriteString("</table>")
				}
				typ = s.Type
				b.WriteString(`<h3>` + esc(s.Type) + ` <span class="muted">(` + esc(s.Source) + `)</span></h3>`)
				b.WriteString(`<table><tr><th>Locale</th><th>Subject</th><th>Preheader</th><th>Files</th></tr>`)
			}
			dir := i18n.Dir(i18n.Normalize(s.Locale))
			loc := esc(s.Locale)
			if s.Fallback != "" {
				loc += ` <span class="muted">(template: ` + esc(s.Fallback) + `)</span>`
			}
			base := fileBase(s)
			b.WriteString(`<tr><td>` + loc + `</td><td dir="` + dir + `">` + esc(s.Subject) + `</td><td dir="` + dir + `" class="muted">` + esc(s.Preheader) +
				`</td><td><a href="` + esc(base) + `.html">html</a> · <a href="` + esc(base) + `.txt">txt</a></td></tr>`)
		}
		if typ != "" {
			b.WriteString("</table>")
		}
	}
	b.WriteString("</body></html>\n")
	return b.String()
}
