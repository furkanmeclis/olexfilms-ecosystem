// IsSystemRole reports whether slug is a protected system role.
func IsSystemRole(slug string) bool {
	switch slug {
	case RoleSuperAdmin, RoleOrganizationUser, RoleOrganizationOwner:
		return true
	default:
		return false
	}
}
